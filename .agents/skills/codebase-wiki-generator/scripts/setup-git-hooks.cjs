#!/usr/bin/env node

/**
 * setup-git-hooks.cjs
 * Installs Git hooks (pre-commit or post-commit) to automatically run
 * the Codebase Wiki synchronizer whenever commits are made.
 * 
 * Usage:
 *   node setup-git-hooks.cjs [--hook-type post-commit|pre-commit] [--wiki-dir <dir>]
 */

const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
let hookType = 'post-commit';
let wikiDir = 'docs/wiki';

for (let i = 0; i < args.length; i++) {
  if (args[i] === '--hook-type' || args[i] === '-t') {
    hookType = args[++i];
  } else if (args[i] === '--wiki-dir' || args[i] === '-w') {
    wikiDir = args[++i];
  } else if (args[i] === '--help' || args[i] === '-h') {
    console.log(`
Git Hook Installer for Codebase Wiki Auto-Sync
Usage:
  node setup-git-hooks.cjs [options]

Options:
  --hook-type, -t <type>  Hook type: 'post-commit' (default) or 'pre-commit'
  --wiki-dir, -w <dir>    Wiki directory (default: docs/wiki)
  --help, -h              Show this help message
    `);
    process.exit(0);
  }
}

const rootDir = process.cwd();
const gitDir = path.join(rootDir, '.git');
const huskyDir = path.join(rootDir, '.husky');

if (!fs.existsSync(gitDir) && !fs.existsSync(huskyDir)) {
  console.error(`❌ No .git or .husky directory found at: ${rootDir}`);
  process.exit(1);
}

const hookScriptContent = `#!/bin/sh
# Auto-generated by codebase-wiki-generator
echo "📚 [Wiki Auto-Sync] Checking for codebase documentation updates..."
node .agents/skills/codebase-wiki-generator/scripts/sync-wiki-on-change.cjs --wiki-dir "${wikiDir}" --git-diff
`;

let installedPath = '';

if (fs.existsSync(huskyDir)) {
  const huskyHook = path.join(huskyDir, hookType);
  fs.writeFileSync(huskyHook, hookScriptContent, { encoding: 'utf8', mode: 0o755 });
  installedPath = huskyHook;
} else if (fs.existsSync(gitDir)) {
  const hooksDir = path.join(gitDir, 'hooks');
  if (!fs.existsSync(hooksDir)) {
    fs.mkdirSync(hooksDir, { recursive: true });
  }
  const gitHook = path.join(hooksDir, hookType);
  fs.writeFileSync(gitHook, hookScriptContent, { encoding: 'utf8', mode: 0o755 });
  installedPath = gitHook;
}

console.log(`✅ Successfully installed ${hookType} hook at: ${installedPath}`);
console.log(`💡 Every time you commit, the wiki will be automatically synchronized with codebase changes!`);
