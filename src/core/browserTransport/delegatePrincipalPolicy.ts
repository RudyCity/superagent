/**
 * Identity boundary for Delegate-CDP MCP calls.
 *
 * Only server-side MCP dispatch code may call runWithAuthenticatedDelegatePrincipal.
 * Never construct the context from tool arguments, clientInfo.name, HTTP headers,
 * or a forwarded Core request; none are proof of the initiating MCP connection.
 */
import { createHash } from "node:crypto";
import { AsyncLocalStorage } from "node:async_hooks";
import { BrowserTransportError } from "./types.js";

type Scope = Readonly<{ origin: "mcp"; principalId?: string }>;
const scope = new AsyncLocalStorage<Scope>();
const sessionPattern = /^[a-zA-Z0-9_-]{16,128}$/;

export type AuthenticatedDelegateMcpConnection = Readonly<{
  /** Random ID generated by the MCP server for THIS authenticated transport. */
  sessionId: string;
  mode: "oauth" | "static-bearer";
  /** Identity from the verified transport, never from a tool argument. */
  subject: string;
}>;

/** Requires a trusted per-connection MCP server call site (not currently wired by legacy handlers). */
export function runWithAuthenticatedDelegatePrincipal<T>(
  identity: AuthenticatedDelegateMcpConnection, task: () => T,
): T {
  if (!identity || !sessionPattern.test(identity.sessionId) ||
      !["oauth", "static-bearer"].includes(identity.mode) ||
      typeof identity.subject !== "string" || !identity.subject.trim()) {
    throw new BrowserTransportError("DELEGATE_MCP_PRINCIPAL_REQUIRED", "Verified MCP connection identity is required.");
  }
  const principalId = "mcp-" + createHash("sha256")
    .update("superagent:delegate-mcp:v1\0" + identity.sessionId).digest("hex").slice(0, 32);
  return scope.run({ origin: "mcp", principalId }, task);
}

/** A request reaching the MCP handler must not silently fall back to a local actor. */
export function runWithDelegateMcpBoundary<T>(task: () => T): T {
  return scope.run(scope.getStore() ?? { origin: "mcp" }, task);
}

export function getDelegateMcpPrincipalId(): string | undefined {
  return scope.getStore()?.principalId;
}

export function isDelegateMcpBoundary(): boolean {
  return scope.getStore()?.origin === "mcp";
}

/**
 * Map an authenticated MCP session to its one actor ID, or reject a claimed
 * agentId. Local/non-MCP callers preserve the historical agentId contract.
 */
export function resolveDelegatePrincipalAgent(
  topLevel: unknown, nested: unknown,
  requireAuthenticated = false,
): string | undefined {
  if (topLevel !== undefined && nested !== undefined && topLevel !== nested)
    throw new BrowserTransportError("DELEGATE_CDP_AGENT_CONFLICT", "Conflicting agentId values.");
  const requested = topLevel ?? nested;
  if (requested !== undefined && (typeof requested !== "string" || requested.length > 96))
    throw new BrowserTransportError("DELEGATE_CDP_AGENT_INVALID", "Invalid agentId.");
  const identity = scope.getStore();
  if (identity?.origin === "mcp") {
    if (!identity.principalId) {
      if (requireAuthenticated || requested !== undefined)
        throw new BrowserTransportError("DELEGATE_MCP_PRINCIPAL_REQUIRED",
          "Delegate session operations need a verified MCP connection principal.");
      return undefined;
    }
    if (requested !== undefined && requested !== identity.principalId)
      throw new BrowserTransportError("DELEGATE_MCP_AGENT_SPOOFED",
        "agentId does not match the authenticated MCP session.");
    return identity.principalId;
  }
  return requested as string | undefined;
}

export function assertDelegateMcpActorForCommand(
  command: string, topLevel: unknown, nested: unknown,
): string | undefined {
  const anonymousRead = new Set([
    "list_targets", "transport_status", "list_sessions", "coordinator_status",
    "snapshot", "read_page", "extract_links", "wait_for", "get_dialogs",
    "get_cursor", "shared_snapshot", "list_file_inputs", "verify_upload",
  ]);
  return resolveDelegatePrincipalAgent(topLevel, nested, !anonymousRead.has(command));
}

export function visibleDelegateSessions<T extends {
  agentId: string; participants?: Array<{ agentId: string }>;
}>(sessions: T[]): T[] {
  const caller = scope.getStore();
  if (!caller) return sessions;
  if (!caller.principalId) return [];
  return sessions.filter(session => session.agentId === caller.principalId ||
    session.participants?.some(member => member.agentId === caller.principalId));
}
