import path from "node:path";
import type { DaemonRunRecord } from "../daemon/daemonTypes.js";
import { listDaemonRuns } from "../storage/daemonRunLedger.js";
import { getWorkspaceId } from "../config/paths.js";
import { getRMemoryClient, getRMemoryProjectId } from "../rmemoryUtil.js";
import { createMemoryRecordMetadata } from "../memoryRecord.js";

type AdvisoryClient = Pick<ReturnType<typeof getRMemoryClient>, "inspectAtomic" | "updateAtomic">;

export interface SkillLearningBridgeResult {
  status: "created" | "already_exists" | "insufficient_evidence";
  memoryId?: string;
  evidenceRunIds: string[];
  memoryProjectId?: string;
}

function sameWorkspace(a: string, b: string): boolean {
  const first = path.resolve(a);
  const second = path.resolve(b);
  return process.platform === "win32"
    ? first.toLowerCase() === second.toLowerCase()
    : first === second;
}

/**
 * Turn only two *consecutive*, terminal failures of the SAME pinned skill/job/
 * workspace into an advisory candidate. Neither successes nor operator
 * cancellation count as failure evidence. This is intentionally not an LLM.
 */
export function selectConsecutiveSkillFailures(
  runs: DaemonRunRecord[],
  input: { jobId: string; workspacePath: string; pinnedSkillVersion: string },
): DaemonRunRecord[] {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*@[a-f0-9]{12}$/.test(input.pinnedSkillVersion)) return [];
  if (!input.workspacePath || !input.jobId) return [];
  const projectId = getWorkspaceId(input.workspacePath);
  const latest = [...runs]
    .filter(run => run.jobId === input.jobId)
    .sort((a, b) => b.startedAt - a.startedAt || b.runId.localeCompare(a.runId))
    .slice(0, 2);

  if (latest.length !== 2) return [];
  if (!latest.every(run =>
    (run.status === "error" || run.status === "timed_out") &&
    run.pinnedSkillVersion === input.pinnedSkillVersion &&
    run.projectId === projectId &&
    sameWorkspace(run.workspacePath, input.workspacePath) &&
    run.completedAt != null
  )) return [];
  if (latest[0].runId === latest[1].runId) return [];
  return latest;
}

export async function bridgeRepeatedSkillFailures(input: {
  jobId: string;
  workspacePath: string;
  pinnedSkillVersion: string;
  runs?: DaemonRunRecord[];
  client?: AdvisoryClient;
}): Promise<SkillLearningBridgeResult> {
  const runs = input.runs ?? listDaemonRuns({ jobId: input.jobId, limit: 2 });
  const failures = selectConsecutiveSkillFailures(runs, input);
  if (failures.length !== 2) return { status: "insufficient_evidence", evidenceRunIds: [] };

  const [name, version] = input.pinnedSkillVersion.split("@");
  const memoryId = "skill-regression-" + name + "-" + version;
  const projectId = getRMemoryProjectId(input.workspacePath);
  const client = input.client ?? getRMemoryClient(3000);
  const existing = await client.inspectAtomic({ id: memoryId, scope: "project", projectId });
  if (existing) {
    // Do not overwrite an already-reviewed/rejected/verified candidate.
    return { status: "already_exists", memoryId, memoryProjectId: projectId,
      evidenceRunIds: failures.map(run => run.runId) };
  }
  const now = new Date().toISOString();
  const metadata = createMemoryRecordMetadata({
    memoryId,
    memoryType: "advisory_lesson",
    scope: "project",
    projectId,
    taskId: input.jobId,
    source: "daemon-skill-learning-bridge",
    validationStatus: "candidate",
    now,
    evidence: failures.map(run => ({
      id: run.runId,
      kind: "task" as const,
      summary: "Daemon run failed",
      status: run.status,
      recordedAt: new Date(run.completedAt!).toISOString(),
    })),
    existingMetadata: {
      assertionKey: "skill_regression_" + name,
      retentionClass: "temporary",
      reviewState: "quarantined",
      quarantineReason: "Autogenerated advisory: owner must review outcome evidence before recall.",
    },
  });
  const content =
    "[project:" + projectId + "] Skill '" + name +
    "' encountered repeated execution failures. Review project-specific preconditions " +
    "and the linked run IDs before invoking or revising this skill. This is unverified advisory evidence.";
  await client.updateAtomic({ id: memoryId, content, metadata });
  const written = await client.inspectAtomic({ id: memoryId, scope: "project", projectId });
  if (!written || written.metadata.validationStatus !== "candidate" ||
      written.metadata.reviewState !== "quarantined" ||
      written.metadata.projectId !== projectId ||
      !Array.isArray(written.metadata.evidence) ||
      failures.some(run => !written.metadata.evidence.some((item: { id?: string }) => item.id === run.runId))) {
    throw new Error("Skill learning advisory persistence could not be verified.");
  }
  return { status: "created", memoryId, memoryProjectId: projectId,
    evidenceRunIds: failures.map(run => run.runId) };
}


/**
 * Link explicit negative user feedback to an owner-review-only memory candidate.
 * The free-form feedback text stays in versioned skill metrics; it is NOT copied
 * into memory or a system prompt. Only a durable feedback ID is cited.
 */
export async function bridgeNegativeSkillFeedback(input: {
  skillName: string;
  skillVersion: string;
  workspacePath: string;
  feedbackId: string;
  client?: AdvisoryClient;
}): Promise<SkillLearningBridgeResult> {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(input.skillName) ||
      !/^[a-f0-9]{12}$/.test(input.skillVersion) ||
      !/^skill-feedback-[a-f0-9-]{36}$/.test(input.feedbackId)) {
    throw new Error("Invalid version-bound negative feedback reference.");
  }
  const projectId = getRMemoryProjectId(input.workspacePath);
  const memoryId = "skill-feedback-" + input.skillName + "-" + input.skillVersion;
  const client = input.client ?? getRMemoryClient(3000);
  const existing = await client.inspectAtomic({ id: memoryId, scope: "project", projectId });
  if (existing) {
    return { status: "already_exists", memoryId, memoryProjectId: projectId,
      evidenceRunIds: [] };
  }
  const metadata = createMemoryRecordMetadata({
    memoryId, memoryType: "advisory_lesson", scope: "project", projectId,
    source: "owner-skill-feedback-learning-bridge", validationStatus: "candidate",
    evidence: [{
      id: input.feedbackId,
      kind: "user_feedback",
      status: "negative",
      summary: "Explicit negative feedback recorded for exact skill version",
    }],
    existingMetadata: {
      assertionKey: "skill_feedback_" + input.skillName,
      retentionClass: "temporary",
      reviewState: "quarantined",
      quarantineReason: "User feedback advisory: owner must review before recall or skill revision.",
    },
  });
  const content =
    "[project:" + projectId + "] Skill '" + input.skillName +
    "' received negative user feedback on immutable version " + input.skillVersion +
    ". Review the linked feedback evidence and preconditions before using or revising it.";
  await client.updateAtomic({ id: memoryId, content, metadata });
  const written = await client.inspectAtomic({ id: memoryId, scope: "project", projectId });
  if (!written || written.metadata.validationStatus !== "candidate" ||
      written.metadata.reviewState !== "quarantined" ||
      !Array.isArray(written.metadata.evidence) ||
      !written.metadata.evidence.some((e: { id?: string }) => e.id === input.feedbackId)) {
    throw new Error("Negative feedback advisory persistence could not be verified.");
  }
  return { status: "created", memoryId, memoryProjectId: projectId, evidenceRunIds: [] };
}
