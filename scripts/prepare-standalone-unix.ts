#!/usr/bin/env bun
/** Prepare a locked portable Core for macOS arm64 / Linux x64 Tauri bundles.
 * Copies only generated inputs into src-tauri/resources/standalone and binaries/.
 * Requires Bun 1.4.2; never installs system-wide software.
 */
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { pruneMuslSharpFromLinuxStandalone } from "./prune-linux-musl-sharp.js";

const root = path.resolve(import.meta.dir, "..");
const tauri = path.join(root, "apps/superagent-tray/src-tauri");
const stage = path.join(tauri, "resources/standalone");
const binDir = path.join(tauri, "binaries");
const marker = ".superagent-generated-standalone";
const target =
  process.platform === "darwin" && process.arch === "arm64" ? "aarch64-apple-darwin" :
  process.platform === "linux" && process.arch === "x64" ? "x86_64-unknown-linux-gnu" : null;

function check(ok: unknown, message: string): asserts ok {
  if (!ok) throw new Error("[standalone-unix] " + message);
}
check(target !== null, "Only macOS arm64 and Linux x64 supported by this packaging script");
check(Bun.version === "1.4.2", "Bun 1.4.2 is required for reproducible builds");
check(fs.existsSync(path.join(root, "dist/cli.js")), "Run bun run build first");
check(fs.existsSync(path.join(tauri, "target/release/superagent")), "Build the native CLI before staging");
const stat = fs.statSync(process.execPath);
check(stat.isFile() && stat.size > 10000000, "Invalid Bun executable source");
if (fs.existsSync(stage)) {
  check(fs.existsSync(path.join(stage, marker)), "Refusing to replace an unknown standalone directory");
  fs.rmSync(stage, { recursive: true, force: true });
}
fs.mkdirSync(stage, { recursive: true });
fs.writeFileSync(path.join(stage, marker), "Generated by scripts/prepare-standalone-unix.ts\n");
function copy(src: string, dest: string) {
  check(fs.existsSync(src), "Missing source: " + src);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.cpSync(src, dest, { recursive: true, force: true });
}
for (const file of ["package.json", "bun.lock"]) copy(path.join(root, file), path.join(stage, file));
for (const folder of ["dist", "patches"]) copy(path.join(root, folder), path.join(stage, folder));
for (const file of ["media_backend.py", "setup_media_backends.py"]) {
  copy(path.join(root, "scripts", file), path.join(stage, "scripts", file));
}
fs.mkdirSync(binDir, { recursive: true });
const runtime = path.join(binDir, "bun-" + target);
copy(fs.realpathSync(process.execPath), runtime);
fs.chmodSync(runtime, 0o755);
const install = spawnSync(runtime, ["install", "--production", "--frozen-lockfile", "--no-progress"], {
  cwd: stage, env: { ...process.env, CI: "true" }, stdio: "inherit", timeout: 600000,
});
check(install.status === 0, "Frozen production dependency installation failed: " + (install.error ?? install.status));
const pruned = pruneMuslSharpFromLinuxStandalone(stage, process.platform, process.arch);
if (pruned.length) console.log("[standalone-unix] Excluded incompatible native platform binaries:", pruned.join(", "));
if (process.platform === "linux") {
  const smoke = spawnSync(runtime, ["-e", "import sharp from 'sharp'; import { createCanvas } from '@napi-rs/canvas'; import { Tokenizer } from 'tokenizers'; if (!sharp.versions?.sharp) throw new Error('GNU sharp native addon unavailable'); const canvas = createCanvas(2, 2); if (canvas.width !== 2 || typeof Tokenizer !== 'function') throw new Error('GNU canvas/tokenizers native addon unavailable'); console.log('GNU_NATIVE_ADDONS_OK', sharp.versions.sharp, canvas.width, typeof Tokenizer);"], {
    cwd: stage, env: { ...process.env, CI: "true" }, stdio: "inherit", timeout: 30000,
  });
  check(smoke.status === 0, "GNU sharp/canvas/tokenizers addon smoke check failed after excluding incompatible platform binaries: " + (smoke.error ?? smoke.status));
}
for (const dep of ["ink", "sharp", "r-memory", "typescript"]) {
  check(fs.existsSync(path.join(stage, "node_modules", dep)), "Missing production dependency: " + dep);
}
const pkg = JSON.parse(fs.readFileSync(path.join(stage, "package.json"), "utf8"));
fs.writeFileSync(path.join(stage, "standalone-manifest.json"), JSON.stringify({
  package: pkg.name, version: pkg.version, platform: process.platform, arch: process.arch,
  target, bunVersion: "1.4.2", cli: "superagent",
  entrypoint: "standalone/dist/cli.js", requiresGlobalBun: false, requiresGlobalNode: false,
}, null, 2) + "\n");
console.log("[standalone-unix] Prepared", target, "package version", pkg.version);
